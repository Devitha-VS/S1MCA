import math
a=20
b=5
print("Square root:",math.sqrt(a))
print("Factorial:",math.factorial(b))
print("power:",math.pow(a,2))
print("Floor Division:",math.floor(65.76))
print("ceiling:",math.ceil(33.3))
print("Absolute value:",math.fabs(-10))
print("Greatest common divisor:",math.gcd(12,18))
print("Remainder:",math.fmod(10,3))
print("Exponential:",math.exp(2))
print("pi:",math.pi)
print("Natural logarithm:",math.log(10))
